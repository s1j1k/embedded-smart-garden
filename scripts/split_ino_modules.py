#!/usr/bin/env python3
"""Split the giant .ino into separate .cpp translation units (OOM fix).

Extra .ino files are concatenated by Arduino — that does NOT reduce peak RAM.
Only separate .cpp files become independent compile units.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BAK = Path("/tmp/embedded-smart-garden.ino.bak")
SRC = ROOT / "embedded-smart-garden.ino"

# Function-body modules (1-based inclusive line ranges from the backup).
MODULES = [
    ("sg_init.cpp", 656, 783, "Pumps / LittleFS / sensors init"),
    ("sg_pump_cal.cpp", 784, 1338, "Pump calibration wizard"),
    ("sg_serial.cpp", 1340, 2064, "Serial commands + dose helpers"),
    ("sg_staged.cpp", 2066, 2386, "StageController bridge"),
    ("sg_control.cpp", 2524, 3342, "Water / pH / nutrient loops"),
    ("sg_sensors.cpp", 3344, 3986, "Sensor reads + print"),
    ("sg_csv.cpp", 3988, 4126, "CSV logging"),
    ("sg_network.cpp", 4128, 4468, "WiFi / NTP / Influx"),
    ("sg_mqtt.cpp", 4470, 5557, "MQTT telemetry"),
]


def lines_of(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines(keepends=True)


def slice_l(lines: list[str], a: int, b: int) -> str:
    return "".join(lines[a - 1 : b])


def main() -> None:
    lines = lines_of(BAK if BAK.exists() else SRC)
    assert len(lines) >= 5550, f"unexpected source size {len(lines)}"

    # --- garden.h: includes + types + extern globals + prototypes ---
    preamble = lines[46:600]  # lines 47-600
    header_decls, state_defs, helper_funcs = split_preamble(preamble)
    prototypes = gather_prototypes(lines)

    garden_h = [
        "#pragma once\n",
        "/* Shared declarations for split embedded-smart-garden modules.\n",
        " * Generated by scripts/split_ino_modules.py — re-run after large moves.\n",
        " */\n\n",
        *header_decls,
        "\n/* ---- helper functions defined in garden_state.cpp ---- */\n",
        *prototypes_from_helpers(helper_funcs),
        "\n/* ---- module prototypes ---- */\n",
        *prototypes,
        "\n",
    ]
    (ROOT / "garden.h").write_text("".join(garden_h), encoding="utf-8")
    print(f"wrote garden.h ({len(garden_h)} chunks)")

    state = [
        '/* Global state + small helpers (single definition TU). */\n',
        '#include "garden.h"\n\n',
        *state_defs,
        "\n",
        *helper_funcs,
    ]
    (ROOT / "garden_state.cpp").write_text("".join(state), encoding="utf-8")
    print("wrote garden_state.cpp")

    for name, a, b, desc in MODULES:
        body = slice_l(lines, a, b)
        # Remove default-arg definitions in .cpp (keep defaults only in prototypes).
        body = re.sub(
            r"(void setCalMqttStatus\(const char\* msg),\s*bool ok\s*=\s*true\)",
            r"\1, bool ok)",
            body,
        )
        text = f'/* {desc} */\n#include "garden.h"\n\n{body}'
        (ROOT / name).write_text(text, encoding="utf-8")
        print(f"wrote {name}: {b - a + 1} lines")

    banner = slice_l(lines, 1, 45)
    setup = slice_l(lines, 605, 654)
    loop = slice_l(lines, 2392, 2522)
    ino = (
        banner
        + "\n"
        + '#include "garden.h"\n\n'
        + setup
        + "\n"
        + loop
        + "\n"
    )
    SRC.write_text(ino, encoding="utf-8")
    print(f"wrote {SRC.name}: {ino.count(chr(10))} lines")


def split_preamble(pre: list[str]) -> tuple[list[str], list[str], list[str]]:
    """Classify preamble lines into header / state defs / helper function bodies."""
    header: list[str] = []
    state: list[str] = []
    helpers: list[str] = []

    i = 0
    while i < len(pre):
        raw = pre[i]
        s = raw.lstrip()

        # Preprocessor, comments, blanks → header
        if (
            not s
            or s.startswith("#")
            or s.startswith("//")
            or s.startswith("/*")
            or s.startswith("*")
            or s.startswith("*/")
        ):
            header.append(raw)
            i += 1
            continue

        # Type definitions (struct / enum) → header
        if s.startswith("struct ") or s.startswith("enum "):
            block, i = consume_braced(pre, i)
            header.extend(block)
            continue

        # Function definition → garden_state.cpp (+ prototype later)
        if looks_like_func_def(pre, i):
            block, i = consume_braced(pre, i)
            helpers.extend(block)
            helpers.append("\n")
            continue

        # Data / object definition → state + extern in header
        if looks_like_data_def(s):
            block, i = consume_stmt(pre, i)
            state.extend(block)
            header.extend(make_extern(block))
            continue

        # Fallback keep in header
        header.append(raw)
        i += 1

    return header, state, helpers


def consume_braced(pre: list[str], i: int) -> tuple[list[str], int]:
    block = [pre[i]]
    depth = pre[i].count("{") - pre[i].count("}")
    i += 1
    # signature may span lines before '{'
    while i < len(pre) and depth == 0 and "{" not in block[-1]:
        block.append(pre[i])
        depth += pre[i].count("{") - pre[i].count("}")
        i += 1
    while i < len(pre) and depth > 0:
        block.append(pre[i])
        depth += pre[i].count("{") - pre[i].count("}")
        i += 1
    return block, i


def consume_stmt(pre: list[str], i: int) -> tuple[list[str], int]:
    if "{" in pre[i] and ";" not in pre[i].split("{", 1)[0]:
        # array / aggregate initializer
        return consume_braced(pre, i)
    block = [pre[i]]
    if ";" in pre[i]:
        return block, i + 1
    i += 1
    while i < len(pre):
        block.append(pre[i])
        if ";" in pre[i]:
            return block, i + 1
        # braced init without ; on first line
        if "{" in pre[i]:
            # back up and use braced consumer from start
            start = i - len(block) + 1
            return consume_braced(pre, start)
        i += 1
    return block, i


def looks_like_func_def(pre: list[str], i: int) -> bool:
    s = pre[i].lstrip()
    if s.startswith("typedef "):
        return False
    # Scan a few lines for ') {' pattern without '=' before '('
    window = "".join(pre[i : i + 6])
    if re.search(r"=\s*[^{\n]", window.split("{")[0]):
        # assignment, not function — unless it's default arg
        if not re.search(r"\([^)]*=[^)]*\)", window.split("{")[0]):
            if "(" not in window.split("=")[0]:
                return False
    head = window.split("{", 1)[0]
    if "(" not in head or ")" not in head:
        return False
    # exclude object constructors: Type name(args);
    if re.match(
        r"^(OneWire|DallasTemperature|DHT|PASCO2Ino|WiFiClient|PubSubClient)\s+\w+\s*\(",
        s,
    ):
        return False
    # exclude if/for/while
    if re.match(r"^(if|for|while|switch)\b", s):
        return False
    # must look like return-type name(
    if not re.match(
        r"^(inline\s+|static\s+)?(const\s+)?(unsigned\s+)?(long\s+)?"
        r"(void|bool|int|float|double|String|char|size_t|uint\d+_t|int\d+_t|"
        r"unsigned|long|short)\b|"
        r"^(inline\s+|static\s+)?(const\s+char\s*\*|GrowPreset\s*&|const\s+GrowPreset\s*&)",
        s,
    ):
        # also: int fill0Percent() etc already covered; const GrowPreset& activePreset()
        if not re.match(r"^(const\s+)?[\w:<>&\s\*]+\s+\w+\s*\(", s):
            return False
    return "{" in window


def looks_like_data_def(s: str) -> bool:
    if re.match(
        r"^(OneWire|DallasTemperature|DHT|PASCO2Ino|Servo|WiFiClient|PubSubClient)\b",
        s,
    ):
        return True
    if re.match(r"^(const\s+)?char\s*\*\s+\w+", s):
        return True
    if re.match(r"^const\s+GrowPreset\b", s):
        return True
    if re.match(
        r"^(const\s+|constexpr\s+|static\s+|volatile\s+|unsigned\s+|signed\s+)*"
        r"(bool|char|short|int|long|float|double|size_t|uint\d+_t|int\d+_t|"
        r"String|PHControlState|NutrientControlState|CalPhase|PumpCal::Id|"
        r"ControlLaw::State|ControlLaw::Mode|ControlLaw::Gains|"
        r"SensorDataStore::WaterLevelTrust|uint8_t)\b",
        s,
    ):
        # not a function
        before = s.split("=", 1)[0]
        if "(" in before and not re.search(r"\w+\s+\w+\s*\([^)]*\)\s*;", s):
            # int foo(... something without being ctor ending ;
            if re.search(r"\w+\s*\([^;]*\)\s*\{?", before) and not re.search(
                r"(OneWire|DHT|Servo)", s
            ):
                return False
        return True
    return False


def make_extern(block: list[str]) -> list[str]:
    text = "".join(block)
    # Objects with ctor args
    m = re.match(
        r"^(\s*)(OneWire|DallasTemperature|DHT|PASCO2Ino|WiFiClient|PubSubClient)"
        r"\s+(\w+)\s*\([\s\S]*?\)\s*;\s*$",
        text,
    )
    if m:
        return [f"{m.group(1)}extern {m.group(2)} {m.group(3)};\n"]
    m = re.match(r"^(\s*)(Servo)\s+(\w+)\s*;\s*$", text)
    if m:
        return [f"{m.group(1)}extern {m.group(2)} {m.group(3)};\n"]

    # Drop initializer
    decl = re.sub(r"=\s*\{[\s\S]*\}\s*;\s*$", ";", text.strip())
    if decl == text.strip():
        decl = re.sub(r"=\s*[^;]*;\s*$", ";", text.strip())
    decl = decl.strip()
    if not decl.endswith(";"):
        decl += ";"
    # const GrowPreset GROW_PRESETS[];  — keep brackets
    if not decl.startswith("extern "):
        decl = "extern " + decl
    return [decl + "\n"]


def prototypes_from_helpers(helpers: list[str]) -> list[str]:
    text = "".join(helpers)
    out: list[str] = []
    # crude: find "type name(...)" before {
    for m in re.finditer(
        r"(^|\n)([^{\n]+?)\s*\{",
        text,
    ):
        sig = m.group(2).strip()
        if not sig or sig.startswith("//") or sig.startswith("#"):
            continue
        if sig.startswith("if ") or sig.startswith("for ") or sig.startswith("while "):
            continue
        if "(" not in sig:
            continue
        # only top-level-looking
        if re.match(
            r"^(inline\s+|static\s+)?(const\s+)?[\w:<>\*& ]+\s+\w+\s*\(",
            sig,
        ):
            # keep default args in prototype
            proto = re.sub(r"\s+", " ", sig) + ";"
            if proto not in out:
                out.append(proto + "\n")
    return out


def gather_prototypes(lines: list[str]) -> list[str]:
    ranges = [(605, 654), (2392, 2522)] + [(a, b) for _, a, b, _ in MODULES]
    out: list[str] = []
    seen: set[str] = set()
    for a, b in ranges:
        i = a - 1
        end = b
        while i < end and i < len(lines):
            if not looks_like_func_def(lines, i):
                i += 1
                continue
            # signature
            sig = ""
            k = i
            while k < len(lines):
                sig += " " + lines[k].rstrip()
                if "{" in lines[k]:
                    break
                k += 1
            sig = sig.split("{", 1)[0].strip()
            sig = re.sub(r"\s+", " ", sig)
            if sig.startswith("static "):
                # file-local — leave undeclared globally
                block, i2 = consume_braced(lines, i)
                i = i2
                continue
            key = re.sub(r"\s*=\s*[^,)]+", "", sig)  # ignore defaults for dedupe
            if key not in seen:
                seen.add(key)
                out.append(sig + ";\n")
            block, i = consume_braced(lines, i)
    return out


if __name__ == "__main__":
    main()
